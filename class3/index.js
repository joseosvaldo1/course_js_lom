console.log('Luiz "Otávio"');       // => Luiz "Otávio"  (String_)
console.log("Luiz 'Otávio'");       // => Luiz 'Otávio'  (String)
console.log(`'Luiz' "Otávio"`);     // => 'Luiz' "Otávio" (String)

